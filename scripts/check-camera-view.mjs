import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {registerHooks} from 'node:module';
import * as THREE from 'three';
registerHooks({resolve(s,c,next){if(s.startsWith('.')&&c.parentURL&&!/\.[a-z]+$/i.test(s)){const p=new URL(s+'.ts',c.parentURL);if(existsSync(p))return next(p.href,c);}return next(s,c);}});
const {INITIAL_VIEW,resetCameraView,orbitAngles,applyCameraView,centerFeetInView}=await import('../src/cameraView.ts');
const {GroundedBackdrop}=await import('../src/groundedBackdrop.ts');
const camera=new THREE.PerspectiveCamera(18,9/16,.5,200);
const scale=.04,focus=128,pivot=new THREE.Vector3(0,(95-focus)*scale,0);
const cfg={...INITIAL_VIEW,exposure:.77,outputMirror:true};
applyCameraView(camera,cfg,scale,focus);
const initialMatrix=camera.matrixWorld.clone(),distance=camera.position.distanceTo(pivot);
Object.assign(cfg,orbitAngles(0,-6,70,18));
applyCameraView(camera,cfg,scale,focus);
assert.ok(Math.abs(camera.position.distanceTo(pivot)-distance)<1e-10,'orbit preserves distance');
assert.ok(pivot.clone().project(camera).lengthSq()>0); // depth remains finite
const projected=pivot.clone().project(camera);
assert.ok(Math.abs(projected.x)<1e-10&&Math.abs(projected.y)<1e-10,'orbit keeps body pivot centered');
const orientation=camera.quaternion.clone(),position=camera.position.clone();
cfg.pViewOffsetXcm=15;cfg.pViewCenterCm=110;
applyCameraView(camera,cfg,scale,focus);
assert.ok(camera.quaternion.angleTo(orientation)<1e-7,'pan preserves orientation');
const motion=camera.position.clone().sub(position).applyQuaternion(orientation.clone().invert());
assert.ok(Math.abs(motion.x-.6)<1e-10&&Math.abs(motion.y-.6)<1e-10&&Math.abs(motion.z)<1e-10,'pan moves in camera plane');
cfg.pViewHeightCm=130;
resetCameraView(cfg);applyCameraView(camera,cfg,scale,focus);
assert.deepEqual(camera.matrixWorld.elements,initialMatrix.elements,'reset recovers initial camera');
assert.equal(cfg.exposure,.77);assert.equal(cfg.outputMirror,true);
assert.deepEqual(orbitAngles(0,-6,1e6,1e6),{cameraYawDeg:-25,cameraTiltDeg:-12});
assert.deepEqual(orbitAngles(0,-6,-1e6,-1e6),{cameraYawDeg:25,cameraTiltDeg:-2});
const bg=new GroundedBackdrop(scale,focus),texture=new THREE.Texture();
assert.equal(bg.root.visible,false);bg.setTexture(texture,16/9);assert.equal(bg.root.visible,true);
const [wall,floor,shadow]=bg.root.children;
assert.equal(wall.material,floor.material,'wall and floor share photo projection');
assert.ok(Math.abs(floor.position.y+focus*scale)<1e-10,'ground aligned with model base');
assert.ok(shadow.position.y>floor.position.y&&shadow.position.y-floor.position.y<.02,'contact shadow above ground');
assert.equal(shadow.material.depthWrite,false);
const photoMatrix=wall.material.uniforms.projection.value;
const expected=new THREE.Matrix4().multiplyMatrices(camera.projectionMatrix,camera.matrixWorldInverse);
assert.deepEqual(photoMatrix.elements,expected.elements,'photo and reset use same reference camera');
bg.setTexture(null,16/9);assert.equal(bg.root.visible,false);
console.log('PASS: body-centered orbit, camera-space pan, reset preserves other preferences, limits, photo projection and contact floor');

for(const yaw of [-25,0,25])for(const tilt of [-12,-6,-2]){
  Object.assign(cfg,{cameraYawDeg:yaw,cameraTiltDeg:tilt,pViewCenterCm:160,pViewOffsetXcm:35,pViewHeightCm:180});
  applyCameraView(camera,cfg,scale,focus);
  const q=camera.quaternion.clone();
  centerFeetInView(camera,cfg,scale,focus);
  const feet=new THREE.Vector3(0,-focus*scale,0).project(camera);
  assert.ok(Math.abs(feet.x)<1e-10&&Math.abs(feet.y)<1e-10,'feet centered after rotation and pan');
  assert.ok(camera.quaternion.angleTo(q)<1e-7,'centering preserves camera direction');
  assert.equal(cfg.pViewHeightCm,180,'centering preserves zoom');
  const position=camera.position.clone();centerFeetInView(camera,cfg,scale,focus);
  assert.ok(position.distanceTo(camera.position)<1e-10,'centering is idempotent');
}
resetCameraView(cfg);applyCameraView(camera,cfg,scale,focus);
assert.deepEqual(camera.matrixWorld.elements,initialMatrix.elements,'reset restores view after feet centering');
console.log('PASS: feet centering preserves angle/zoom, repeated action and reset');
