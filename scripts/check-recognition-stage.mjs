import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
import {existsSync,readFileSync} from 'node:fs';
registerHooks({resolve(s,c,next){if(s.startsWith('.')&&c.parentURL&&!/\.[a-z]+$/i.test(s)){const p=new URL(s+'.ts',c.parentURL);if(existsSync(p))return next(p.href,c);}return next(s,c);}});
const {RecognitionGate,DEFAULT_RECOGNITION,personInRecognitionRange}=await import('../src/recognitionGate.ts');
const {SignalProcessor,emptySignal}=await import('../src/signals.ts');
const {MimicStateMachine}=await import('../src/state.ts');
const cfg=JSON.parse(readFileSync('public/config.json'));
const opts=structuredClone(DEFAULT_RECOGNITION),presence={faceLostHoldMs:600};
const person={x:.3,y:.1,w:.4,h:.8,score:.9};
const face=(cx=.5,h=.15)=>({bbox:{x:cx-.06,y:.2,w:.12,h,cx,cy:.2+h/2},yaw:20,pitch:0,roll:0,blend:{}});
const track=(t,f=face())=>({faces:f?[f]:[],inferenceMs:1,observedAtMs:t});
const gate=new RecognitionGate(opts,presence);
assert.equal(gate.update(null,track(0,null),0,1,false).stage,0);
assert.equal(gate.update({...person,w:.01},track(50),50,1,false).stage,0);
const small={...person,w:.1,h:.4};assert.equal(gate.update(small,track(100),100,1,false).stage,1);
for(const t of [200,300,400,500])assert.equal(gate.update(person,track(t),t,1,false).stage,1);
assert.equal(gate.update(person,track(600),600,1,false).stage,2);
assert.equal(gate.update(person,track(700,null),700,1,false).stage,2,'brief face loss has grace');
assert.equal(gate.update(person,track(1200,null),1200,1,false).stage,1,'body alone cannot sustain confirmation');
gate.reset();gate.update(person,track(0),0,1,false);
for(let t=16;t<1500;t+=16)assert.equal(gate.update(person,track(0),t,1,false).stage,1,'cached face cannot acquire');
gate.reset();for(const t of [0,100,200,300,400])gate.update(person,track(t),t,1,false);
assert.equal(gate.status.stage,2);assert.equal(gate.update(person,track(500,face(.5,.02)),500,1,false).stage,1,'visible small face returns to preparation');
for(const aspect of [9/16,1,16/9]){
 const g=new RecognitionGate(opts,presence),f=face(.5,.08*Math.min(1,aspect));
 for(const t of [0,100,200,300,400])g.update(person,track(t,f),t,aspect,false);
 assert.equal(g.status.stage,2,'short-side face size agrees across orientation');
}
const margins={...opts,margins:{left:.3,right:.05,top:.1,bottom:.1}};
const left={x:.05,y:.2,w:.2,h:.5,score:.9};
assert.equal(personInRecognitionRange(left,margins,false),false);
assert.equal(personInRecognitionRange(left,margins,true),true,'margins follow mirrored preview');
assert.equal(personInRecognitionRange({x:0,y:.1,w:.9,h:.8,score:.9},opts,false),true,'arms may extend beyond margins');
const hysteresis=new RecognitionGate({...opts,activeArea:.1},presence);
for(const t of [0,100,200,300,400])hysteresis.update(person,track(t),t,1,false);
assert.equal(hysteresis.update({...person,w:.12,h:.75},track(500),500,1,false).stage,2,'small size drift retains active state');
assert.equal(hysteresis.update({...person,w:.1,h:.75},track(600),600,1,false).stage,1,'larger retreat returns to preparation');
hysteresis.reset();assert.equal(hysteresis.update(person,track(700),700,1,false).stage,1,'new owner must confirm again');
assert.equal(new MimicStateMachine(cfg,50000).update(emptySignal(),50000).state,'IDLE','new session starts its own idle timer');
const fsm=new MimicStateMachine(cfg),none=emptySignal();
assert.equal(fsm.update(none,0,false,true).state,'PREPARE');
assert.equal(fsm.update(none,500,false,true).state,'PREPARE');
assert.equal(fsm.update({...none,present:true},600,false,false).state,'ENTER');
assert.equal(fsm.update({...none,present:true},600+cfg.character.enterDurationMs,false,false).state,'MIMIC');
assert.equal(fsm.update(none,2000,false,true).state,'PREPARE');
assert.equal(fsm.update(none,2100,false,false).state,'IDLE');
const processor=new SignalProcessor(cfg);
processor.update(track(0,face(.2)),0);processor.update(track(100,face(.85)),100);
assert.equal(processor.target.cx,.85,'YOLO-owned face has no second spatial lock');
const ambiguous=new SignalProcessor(cfg);assert.equal(ambiguous.update({...track(0),faces:[face(.2),face(.8)]},0).present,false,'do not choose a second owner from multiple faces');
console.log('PASS: 0/1/2 stages, mirrored margins, person/face sizes, face confirmation, cached input, dropout, preparation FSM, single-owner face processing');
